import { legendGradient, legendPosition, PALETTES } from "../lib/palette";
import type { TrendMapEntry } from "../types/contracts";

type Props = {
  entry: TrendMapEntry;
};

export function TrendMapLegend({ entry }: Props) {
  const { legend, palette } = entry;
  const spec = PALETTES[palette];
  const ticks = [legend.min, 0, legend.max];
  const significanceRule = entry.fdr
    ? `p ≥ ${entry.alpha} after false discovery rate (FDR) correction`
    : `p ≥ ${entry.alpha}`;

  return (
    <div className="trend-map__legend">
      <div className="trend-map__legend-header">
        <strong>{entry.title}</strong>
        {entry.is_sample && <span className="trend-map__badge">Sample data</span>}
      </div>

      <div
        className="trend-map__gradient"
        role="img"
        aria-label={`Color scale from ${legend.min} to ${legend.max} ${entry.slope_units}, neutral at 0. ${spec.negativeLabel}; ${spec.positiveLabel}.`}
        style={{ background: legendGradient(palette, legend) }}
      />

      <div className="trend-map__ticks">
        {ticks.map((tick) => (
          <span
            key={tick}
            className="trend-map__tick"
            style={{ left: `${legendPosition(tick, legend) * 100}%` }}
          >
            {tick.toFixed(2)}
          </span>
        ))}
      </div>

      <div className="trend-map__scale-labels">
        <span>{spec.negativeLabel}</span>
        <span>{spec.positiveLabel}</span>
      </div>

      <p className="trend-map__units">
        Trend in {entry.slope_units} · {entry.units} · {entry.period[0]} to {entry.period[1]}
      </p>
      <p className="trend-map__note">
        Faded gray areas are not statistically significant ({significanceRule}).
      </p>
      {entry.is_sample && (
        <p className="trend-map__note">
          Sample data for the interface; maps generated by the pipeline will replace it.
        </p>
      )}
    </div>
  );
}
